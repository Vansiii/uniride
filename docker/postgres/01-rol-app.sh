#!/bin/sh
# Crea el rol de la API: sin dueño de tablas ni BYPASSRLS, para que RLS se aplique (A-13).
set -e
psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" <<SQL
CREATE ROLE uniride_app LOGIN PASSWORD '$POSTGRES_APP_PASSWORD' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
GRANT CONNECT ON DATABASE $POSTGRES_DB TO uniride_app;
GRANT USAGE ON SCHEMA public TO uniride_app;
ALTER DEFAULT PRIVILEGES FOR ROLE $POSTGRES_USER IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO uniride_app;
SQL
